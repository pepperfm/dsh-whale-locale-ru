/** Anchored UI templates. Captured names, amounts, URLs and diagnostic details remain verbatim. */
export function translateWhaleUiText(value, dictionary, defaultContent = {}) {
  const text = value.trim();
  let result = dictionary[text];
  if (result === undefined) {
    const rules = [
      [/^((?:[¥$€£₽]\s*)?[-\d,.\s]+(?:[A-Z]{3})?) · 今日 (.+)$/, (_, balance, today) => `${balance} · сегодня ${today}`],
      [/^余额 —（无接口·按事件）· 今日 (.+)$/, (_, today) => `Баланс — (нет API) · сегодня ${today}`],
      [/^余额 —（该厂商无余额接口，按会话事件估算）· 今日已用 (.+)$/, (_, today) => `Баланс — (нет API; оценка по запросам) · сегодня ${today}`],
      [/^余额 —（无接口·按会话事件）· 今日已用 (.+)$/, (_, today) => `Баланс — (нет API; оценка по запросам) · сегодня ${today}`],
      [/^余额 (.+) · 今日已用 (.+)$/, (_, balance, today) => `Баланс ${balance} · сегодня ${today}`],

      [/^厂商额度 (.+)$/, (_, quota) => `Лимит провайдера: ${quota}`],
      [/^额度 (.+) · 剩 (.+)$/, (_, used, left) => `Лимит ${used} · осталось ${left}`],
      [/^额度 (.+)$/, (_, quota) => `Лимит ${quota}`],
      [/^余额 ≤ (.+) 时提醒$/, (_, amount) => `Уведомлять при балансе ≤ ${amount}`],
      [/^今日已用 ≥ (.+) 时提醒$/, (_, amount) => `Уведомлять при расходах за день ≥ ${amount}`],
      [/^当前自动统计：已用 (.+) · 今日 (.+) tokens$/, (_, used, today) => `Автоучёт: использовано ${used} · сегодня ${today} токенов`],
      [/^跟随保底（(.+)）$/, (_, name) => `По умолчанию (${name === '经典（内置）' ? 'классическая рамка' : name})`],
      [/^泡泡框：(.+)$/, (_, name) => `Рамка: ${name === '经典（内置）' ? 'классическая' : name}`],
      [/^泡泡框（保底）：(.+)$/, (_, name) => `Основная рамка: ${name === '经典（内置）' ? 'классическая' : name}`],
      [/^(.+?)（内置，只读）$/, (_, name) => `${name} (встроенный, только чтение)`],
      [/^(.+?)（内置）$/, (_, name) => `${name} (встроенный)`],
      [/^编辑泡泡框：(.+)$/, (_, name) => `Изменить рамку: ${name}`],
      [/^随机图片\((\d+)张\)$/, (_, count) => `Случайные изображения (${count})`],
      [/^随机语句\((\d+)条\)$/, (_, count) => `Случайные фразы (${count})`],
      [/^对话名\(保留 (\d+) 字\)$/, (_, count) => `Название диалога (до ${count} символов)`],
      [/^对话名\(不截断\)$/, () => 'Название диалога (целиком)'],
      [/^余额·(.+)$/, (_, name) => `Баланс · ${name}`],
      [/^今日已用·(.+)$/, (_, name) => `Расходы за день · ${name}`],
      [/^额度·(.+)$/, (_, name) => `Лимит · ${name}`],
      [/^文本: (.*)$/, (_, content) => `Текст: ${defaultContent[content] ?? content}`],
      [/^超链接: (.*)$/, (_, content) => `Ссылка: ${content}`],
      [/^自定义内容 · (\d+)个模块$/, (_, count) => `Свои облачка · модулей: ${count}`],
      [/^第 (\d+) 次点击$/, (_, count) => `Нажатие ${count}`],
      [/^已选 (\d+) 个$/, (_, count) => `Выбрано: ${count}`],
      [/^确定删除音效组「(.*)」吗？$/, (_, name) => `Удалить набор звуков «${name}»?`],
      [/^确定删除音频「(.*)」吗？$/, (_, name) => `Удалить аудио «${name}»?`],
      [/^确定删除角色「(.*)」吗？$/, (_, name) => `Удалить персонажа «${name}»?`],
      [/^删除失败[:：] ?(.+)$/, (_, detail) => `Не удалось удалить: ${detail}`],
      [/^保存失败[:：] ?(.+)$/, (_, detail) => `Не удалось сохранить: ${detail}`],
      [/^导入失败[:：] ?(.+)$/, (_, detail) => `Не удалось импортировать: ${detail}`],
      [/^请求失败[:：] ?(.+)$/, (_, detail) => `Ошибка запроса: ${detail}`],
      [/^读取失败[:：] ?(.+)$/, (_, detail) => `Не удалось прочитать: ${detail}`],
      [/^加载失败[:：] ?(.+)$/, (_, detail) => `Не удалось загрузить: ${detail}`],
      [/^模型设置 · ([\s\S]*)$/, (_, name) => `Настройки модели · ${name}`],
      [/^额度 · ([\s\S]*)$/, (_, name) => `Лимит · ${name}`],
      [/^(Codex|自动|手动) · 已用 ([\d.]+%) · 剩 (.+)$/, (_, mode, used, left) => `${({Codex:'Codex','自动':'Авто','手动':'Вручную'})[mode]} · использовано ${used} · осталось ${left}`],
      [/^(\d+)天(\d+)小时后重置$/, (_, d, h) => `Сброс через ${d} д ${h} ч`],
      [/^(\d+)小时(\d+)分后重置$/, (_, h, m) => `Сброс через ${h} ч ${m} мин`],
      [/^Codex 今日 (.+) · 近7天 (.+) tokens$/, (_, today, week) => `Codex: сегодня ${today} · 7 дней ${week} токенов`],
      [/^校正后消费：(.+)$/, (_, amount) => `Расход после корректировки: ${amount}`],
      [/^余额暂未刷新：([\s\S]*)$/, (_, error) => `Баланс пока не обновлён: ${error}`],
      [/^共 (\d+) 笔明细(?: · 峰值 (\d{4}-\d{2}-\d{2}) (.+))?$/, (_, count, date, amount) => `Операций: ${count}${date ? ` · максимум ${date} ${amount}` : ''}`],
      [/^本地估算：(-?\d+\.\d{8}) CNY$/, (_, amount) => `Локальная оценка: ${amount} CNY`],
      [/^… 该日共 (\d+) 条,仅显示前 (\d+) 条$/, (_, all, count) => `… За день: ${all}; показаны первые ${count}`],
      [/^加载更早记录\(还剩 (\d+) 天\)$/, (_, days) => `Ранние записи (осталось дней: ${days})`],
      [/^角色 (\d+) · 泡泡图 (\d+)$/, (_, roles, images) => `Персонажи: ${roles} · изображения: ${images}`],
      [/^音效组 (\d+) · 片段 (\d+)$/, (_, groups, clips) => `Наборы звуков: ${groups} · фрагменты: ${clips}`],
      [/^按压:(.*) 松开:(.*)$/, (_, down, up) => `Нажатие: ${down} · отпускание: ${up}`],
      [/^第(\d+)次点击 · 编辑内容$/, (_, count) => `Нажатие ${count} · изменить содержимое`],
      [/^([AB]) 泡\(权重 (\d+)\)$/, (_, option, weight) => `Облачко ${option} (вес ${weight})`],
      [/^从模块库删除「([\s\S]*)」\?$/, (_, name) => `Удалить из библиотеки модуль «${name}»?`],
      [/^置顶序号 (\d+)$/, (_, number) => `Порядок закрепления: ${number}`],
      [/^(\d+\.\d)s – (\d+\.\d)s（共 (\d+\.\d)s，缩放 x(\d+\.\d)）$/, (_, start, end, duration, zoom) => `${start} с – ${end} с (всего ${duration} с; масштаб x${zoom})`],
      [/^✓ 测试通过\n([\s\S]*)$/, (_, detail) => `✓ Проверка пройдена\n${detail}`],
      [/^⚠ 测试失败\n([\s\S]*)$/, (_, detail) => `⚠ Проверка не пройдена\n${detail}`],
      [/^✓ 保存成功：([\s\S]*)\n已加入模型列表$/, (_, name) => `✓ Сохранено: ${name}\nДобавлено в список моделей`],
      [/^已同时移除 (\d+) 个引用该模型的泡泡模块$/, (_, count) => `Также удалено модулей облачков: ${count}`],
      [/^(已观测消费|已校正消费|本地估算|旧版记录 · 未校正) (.+)$/, (_, label, amount) => `${({'已观测消费':'Наблюдаемые расходы','已校正消费':'Скорректированные расходы','本地估算':'Локальная оценка','旧版记录 · 未校正':'Старая запись · без корректировки'})[label]} ${amount}`],
      [/^点这一行展开 \/ 收起「(图片|音频)」的资源$/, (_, kind) => `Развернуть / свернуть ${kind === '图片' ? 'изображения' : 'аудио'}`],
      [/^点这一行展开 \/ 收起「(内容显示范围与位移|形状与内容|外观)」(（内容显示范围 = 文字只会落在这个矩形里；位移 = 这个槽位的 x\/y 微调）)?$/, (_, label, detail) => `Развернуть / свернуть «${dictionary[label] ?? label}»${detail ? ' (область ограничивает текст; смещение корректирует x/y)' : ''}`],
      [/^首次点击 · 编辑内容$/, () => 'Первое нажатие · изменить'],
      [/^([AB]) · 编辑内容$/, (_, option) => `${option} · изменить`],
      [/^点击编辑该泡泡的内容模块\(自定义内容 · (\d+)个模块\)$/, (_, count) => `Изменить содержимое облачка (модулей: ${count})`],
      [/^点击编辑该泡\(自定义内容 · (\d+)个模块\);按住拖动可把该泡拆出到其他位置$/, (_, count) => `Изменить облачко (модулей: ${count}); перетащите, чтобы вынести его в другую позицию`],
      [/^可用模型 (\d+) 个$/, (_, count) => `Доступных моделей: ${count}`],
      [/^(凭据读取失败|余额接口请求失败|额度接口请求失败|余额服务异常|测试失败): ([\s\S]*)$/, (_, kind, detail) => `${({'凭据读取失败':'Не удалось прочитать учётные данные','余额接口请求失败':'Ошибка запроса баланса','额度接口请求失败':'Ошибка запроса лимитов','余额服务异常':'Ошибка сервиса баланса','测试失败':'Проверка не пройдена'})[kind]}: ${detail}`],
      [/^加载中…$/, () => 'Загрузка…'],
      [/^⚠ 设置保存失败[:：] ?(.+)$/, (_, detail) => `⚠ Не удалось сохранить настройки: ${detail}`]
    ];
    for (const [pattern, render] of rules) {
      const match = pattern.exec(text);
      if (match) { result = render(...match); break; }
    }
  }
  if (result === undefined || result === text) return value;
  return value.slice(0, value.indexOf(text)) + result + value.slice(value.indexOf(text) + text.length);
}
